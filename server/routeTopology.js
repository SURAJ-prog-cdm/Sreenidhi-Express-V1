/** Normalize route identifier: 'Route 14 (Secunderabad)' -> 'route-14' */
export function normalizeRouteTopologyId(s) {
  const m = /(\d+)/.exec(String(s ?? ''));
  return m ? `route-${parseInt(m[1], 10)}` : String(s ?? '').trim().toLowerCase();
}

/**
 * Resolves a pickup stop name, id, or alias to a canonical stop & area cluster.
 * Returns { stopId, stopName, areaClusterId, areaClusterName, lat, lng, sequence } or null.
 */
export function resolveStopForStudent(routeId, pickupStopText) {
  if (!pickupStopText || typeof pickupStopText !== 'string') return null;
  const normRoute = normalizeRouteTopologyId(routeId);
  const route = ROUTE_TOPOLOGY[normRoute] || ROUTE_TOPOLOGY['route-51'] || ROUTE_TOPOLOGY['route-14'];
  if (!route) return null;

  const raw = pickupStopText.trim();
  const lower = raw.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();

  // 1. Direct match on stop.id (case-insensitive)
  const byId = route.stops.find((s) => s.id.toLowerCase() === raw.toLowerCase());
  if (byId) {
    return {
      stopId: byId.id,
      stopName: byId.name,
      areaClusterId: byId.areaClusterId,
      areaClusterName: byId.areaClusterName,
      lat: byId.lat,
      lng: byId.lng,
      sequence: byId.sequence,
    };
  }

  // 2. Exact match on stop.name or stop.shortName
  const byName = route.stops.find(
    (s) => s.name.toLowerCase() === raw.toLowerCase() || s.shortName.toLowerCase() === raw.toLowerCase()
  );
  if (byName) {
    return {
      stopId: byName.id,
      stopName: byName.name,
      areaClusterId: byName.areaClusterId,
      areaClusterName: byName.areaClusterName,
      lat: byName.lat,
      lng: byName.lng,
      sequence: byName.sequence,
    };
  }

  // 3. Exact alias match
  for (const stop of route.stops) {
    for (const alias of stop.aliases || []) {
      const aliasNorm = alias.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();
      if (lower === aliasNorm) {
        return {
          stopId: stop.id,
          stopName: stop.name,
          areaClusterId: stop.areaClusterId,
          areaClusterName: stop.areaClusterName,
          lat: stop.lat,
          lng: stop.lng,
          sequence: stop.sequence,
        };
      }
    }
  }

  // 4. Substring alias match (prefer longer aliases)
  let bestMatch = null;
  let bestMatchLen = 0;
  for (const stop of route.stops) {
    for (const alias of stop.aliases || []) {
      const aliasNorm = alias.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();
      if (aliasNorm.length >= 4 && (lower.includes(aliasNorm) || aliasNorm.includes(lower))) {
        if (aliasNorm.length > bestMatchLen) {
          bestMatchLen = aliasNorm.length;
          bestMatch = {
            stopId: stop.id,
            stopName: stop.name,
            areaClusterId: stop.areaClusterId,
            areaClusterName: stop.areaClusterName,
            lat: stop.lat,
            lng: stop.lng,
            sequence: stop.sequence,
          };
        }
      }
    }
  }
  if (bestMatch) return bestMatch;

  // 5. Fallback search across all defined routes if not found on current route
  for (const [rKey, rObj] of Object.entries(ROUTE_TOPOLOGY)) {
    if (rKey === normRoute) continue;
    for (const stop of rObj.stops) {
      if (stop.id.toLowerCase() === raw.toLowerCase()) {
        return {
          stopId: stop.id,
          stopName: stop.name,
          areaClusterId: stop.areaClusterId,
          areaClusterName: stop.areaClusterName,
          lat: stop.lat,
          lng: stop.lng,
          sequence: stop.sequence,
        };
      }
      for (const alias of stop.aliases || []) {
        const aliasNorm = alias.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();
        if (lower === aliasNorm || lower.includes(aliasNorm)) {
          return {
            stopId: stop.id,
            stopName: stop.name,
            areaClusterId: stop.areaClusterId,
            areaClusterName: stop.areaClusterName,
            lat: stop.lat,
            lng: stop.lng,
            sequence: stop.sequence,
          };
        }
      }
    }
  }

  return null;
}

export function getRouteStops(routeId) {
  const norm = normalizeRouteTopologyId(routeId);
  return ROUTE_TOPOLOGY[norm]?.stops || ROUTE_TOPOLOGY['route-51']?.stops || ROUTE_TOPOLOGY['route-14'].stops;
}

export function getRouteClusters(routeId) {
  const norm = normalizeRouteTopologyId(routeId);
  return ROUTE_TOPOLOGY[norm]?.clusters || ROUTE_TOPOLOGY['route-51']?.clusters || ROUTE_TOPOLOGY['route-14'].clusters;
}

